// Produce one readable ESM component, externalizing only npm dependencies.
import { build } from 'rolldown';
import { cp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('..', import.meta.url));
const output = resolve(root, 'exports/perfume-component');
await mkdir(resolve(output, 'public/perfume-assets'), { recursive: true });
await build({
  input: resolve(root, 'src/components/portable/index.js'),
  external: id => /^(react|three|animejs)(\/|$)/.test(id),
  // The output banner explicitly preserves the client boundary for Next.js.
  onwarn(warning, warn) { if (warning.code !== 'MODULE_LEVEL_DIRECTIVE') warn(warning); },
  transform: { jsx: 'react-jsx' },
  output: {
    file: resolve(output, 'PerfumeBottle.js'), format: 'esm', minify: false,
    banner: `'use client';\n// Two Souls: portable React + Three.js + Anime.js perfume experience.\n// Install: npm install react react-dom three@0.171.0 animejs@4.5.0\n// All local model, shader, liquid, animation and UI helpers are included below.`,
  },
});
for (const file of ['studio-small-03-2k.hdr', 'noir-oud-photographic.png', 'STUDIO-LICENSE.md']) {
  await cp(resolve(root, 'public/media', file), resolve(output, 'public/perfume-assets', file));
}
for (const file of ['README.md', 'package.json', 'package-lock.json', 'index.html', 'demo.jsx']) {
  await cp(resolve(root, 'reusable', file), resolve(output, file));
}
// Keep a small provenance note without embedding any local paths or hosting IDs.
await writeFile(resolve(output, 'ASSETS.md'), `The HDR environment is CC0; see public/perfume-assets/STUDIO-LICENSE.md.\nThe fallback image is a generated Two Souls product concept, not a product photograph.\nLabels, material maps, geometry, liquid and mist are generated by the component.\n`);
const source = await readFile(resolve(output, 'PerfumeBottle.js'), 'utf8');
if (/from ['"]\.\.?\//.test(source) || source.includes('renderPerfumeFrame')) {
  throw new Error('Export still contains a local dependency or a global capture hook.');
}
console.log(`Exported ${output}/PerfumeBottle.js (${Math.round(source.length / 1024)} KB) and demo/assets.`);
